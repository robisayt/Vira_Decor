/** Швидкість малювання однієї лінії — однакова для всіх ілюстрацій. */
const DURATION = 0.55;
/** Базовий крок між лініями; для щільніших ілюстрацій трохи ущільнюється,
 *  щоб загальна тривалість була однаковою, а сама лінія малювалась так само. */
const STEP = 0.085;
const TOTAL_TARGET = 2.1;

type Props = {
  id: DirectionArtId;
  /** Малювати лінію по кроках. false — одразу фінальний стан. */
  draw?: boolean;
  /**
   * Спрощений варіант для малого розміру: лише основні контури, без дрібних
   * деталей, які на 100 px усе одно зливаються в пляму.
   */
  compact?: boolean;
  className?: string;
};

/** Скільки перших ліній залишати у спрощеному варіанті. */
const COMPACT_LINES = 10;

export default function DirectionArt({
  id,
  draw = false,
  compact = false,
  className,
}: Props) {
  const reduce = useReducedMotion();
  const strokes = compact ? STROKES[id].slice(0, COMPACT_LINES) : STROKES[id];
  const fills = compact ? [] : FILLS[id];
  const animate = draw && !reduce;
  const step = Math.min(STEP, TOTAL_TARGET / Math.max(strokes.length, 1));
  const total = strokes.length * step + DURATION;

  return (
    <svg
      viewBox="0 0 400 400"
      fill="none"
      aria-hidden
      className={cn("h-full w-full", className)}
      strokeLinecap="round"
      strokeLinejoin="round"
    >
      {fills.map((fill, index) =>
        animate ? (
          <motion.path
            key={`f-${fill.d}`}
            d={fill.d}
            className={fill.tone === "wine" ? "fill-wine/[0.09]" : "fill-clay/[0.11]"}
            initial={{ opacity: 0 }}
            animate={{ opacity: 1 }}
            transition={{ duration: 0.8, ease: silk, delay: total + index * 0.12 }}
          />
        ) : (
          <path
            key={`f-${fill.d}`}
            d={fill.d}
            className={fill.tone === "wine" ? "fill-wine/[0.09]" : "fill-clay/[0.11]"}
          />
        ),
      )}

      {strokes.map((d, index) =>
        animate ? (
          <motion.path
            key={d}
            d={d}
            stroke="currentColor"
            strokeWidth={1.3}
            vectorEffect="non-scaling-stroke"
            initial={{ pathLength: 0, opacity: 0 }}
            animate={{ pathLength: 1, opacity: 1 }}
            transition={{
              pathLength: { duration: DURATION, ease: silk, delay: index * step },
              opacity: { duration: 0.15, delay: index * step },
            }}
          />
        ) : (
          <path
            key={d}
            d={d}
            stroke="currentColor"
            strokeWidth={1.3}
            vectorEffect="non-scaling-stroke"
          />
        ),
      )}
    </svg>
  );
}
